/**
 * Tests for writing the product version into every manifest (`node --test scripts/`).
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { collectVersions } from "./release-version.mjs";
import { setCargoLockVersions, setCargoWorkspaceVersion, setJsonVersion, setProductVersion } from "./set-version.mjs";

const CARGO_TOML = `[workspace]
resolver = "2"
members = ["crates/a"]

[workspace.package]
version = "2.0.0"
edition = "2021"

[workspace.dependencies]
serde = { version = "1.0" }
`;

const CARGO_LOCK = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "a"
version = "2.0.0"
dependencies = [
 "serde",
]

[[package]]
name = "serde"
version = "2.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "abc"

[[package]]
name = "symphony-core"
version = "2.0.0"
`;

function fixture() {
  const root = mkdtempSync(join(tmpdir(), "set-version-"));
  const write = (file, text) => {
    mkdirSync(dirname(join(root, file)), { recursive: true });
    writeFileSync(join(root, file), text);
  };
  write("Cargo.toml", CARGO_TOML);
  write("Cargo.lock", CARGO_LOCK);
  write("package.json", '{\n  "name": "root",\n  "version": "2.0.0",\n  "private": true\n}\n');
  write("apps/desktop/package.json", '{\n  "name": "@symphony/desktop",\n  "version": "2.0.0",\n  "dependencies": {\n    "x": "1"\n  }\n}\n');
  write(
    "apps/desktop/src-tauri/tauri.conf.json",
    '{\n  "$schema": "https://schema.tauri.app/config/2",\n  "version": "2.0.0",\n  "bundle": { "version": "2.0.0" }\n}\n'
  );
  return root;
}

test("the workspace version is replaced and the rest of Cargo.toml is kept", () => {
  const next = setCargoWorkspaceVersion(CARGO_TOML, "2.0.1");
  assert.match(next, /\[workspace\.package\]\nversion = "2\.0\.1"\nedition/);
  assert.equal(next.replace('version = "2.0.1"', 'version = "2.0.0"'), CARGO_TOML);
});

test("only the top-level version of a JSON manifest changes", () => {
  const text = '{\n  "version": "2.0.0",\n  "nested": {\n    "version": "2.0.0"\n  }\n}\n';
  assert.equal(setJsonVersion(text, "2.0.1"), '{\n  "version": "2.0.1",\n  "nested": {\n    "version": "2.0.0"\n  }\n}\n');
});

test("Cargo.lock moves the workspace crates and keeps registry packages", () => {
  const next = setCargoLockVersions(CARGO_LOCK, "2.0.0", "2.0.1");
  assert.match(next, /name = "a"\nversion = "2\.0\.1"/);
  assert.match(next, /name = "symphony-core"\nversion = "2\.0\.1"/);
  assert.match(next, /name = "serde"\nversion = "2\.0\.0"\nsource/);
  assert.match(next, /^version = 4$/m);
});

test("setProductVersion writes every manifest and collectVersions agrees afterwards", () => {
  const root = fixture();
  try {
    const changed = setProductVersion(root, "2.0.1").sort();
    assert.deepEqual(changed, [
      "Cargo.lock",
      "Cargo.toml",
      "apps/desktop/package.json",
      "apps/desktop/src-tauri/tauri.conf.json",
      "package.json"
    ]);
    const versions = collectVersions(root);
    assert.ok(versions.length >= 4);
    assert.deepEqual([...new Set(versions.map((v) => v.version))], ["2.0.1"]);
    assert.equal(readFileSync(join(root, "apps/desktop/src-tauri/tauri.conf.json"), "utf8").includes('"bundle": { "version": "2.0.0" }'), true);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("setProductVersion rejects anything that is not x.y.z", () => {
  const root = fixture();
  try {
    assert.throws(() => setProductVersion(root, "2.0.1-rc.1"), /must be x\.y\.z/);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});
