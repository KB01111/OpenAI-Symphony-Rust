//! Checked TypeScript contract generation.
//!
//! The Rust types serialized over `/api/v1/*` are the single source of truth for the frontend.
//! This test renders their TypeScript declarations with `ts-rs` and fails when
//! `packages/shared-types/src/generated/contracts.ts` is stale.
//!
//! Regenerate with:
//! `UPDATE_TS_CONTRACTS=1 cargo test -p symphony-server --test ts_contract`

use std::path::PathBuf;

use symphony_core::{domain::*, AgentConfig, CodexConfig, HooksConfig, ServiceConfig};
use symphony_orchestrator::{
    AttemptSummary, IssueDetailResponse, ProjectUpdate, RefreshResponse, WorkflowDocument,
    WorkflowValidation, WorkspaceInfo,
};
use symphony_server::{
    ApiErrorBody, ApiErrorDetail, CancelTaskRequest, CreateProjectRequest, CreateTaskRequest,
    CredentialKeysResponse, CredentialSavedResponse, DecideApprovalRequest, HealthResponse,
    ListTasksQuery, MoveTaskStatusRequest, PreviewWorkflowRequest, SchedulerStateResponse,
    SetCredentialRequest, StreamControlEvent, UpdateWorkflowRequest, ValidateRepositoryRequest,
};
use ts_rs::{Config, TS};

fn generate() -> String {
    let cfg = Config::new().with_large_int("number");
    let mut out = String::from(
        "// AUTO-GENERATED by crates/symphony-server/tests/ts_contract.rs. DO NOT EDIT.\n\
         // Regenerate: UPDATE_TS_CONTRACTS=1 cargo test -p symphony-server --test ts_contract\n\n\
         export type JsonValue = number | string | boolean | Array<JsonValue> | { [key in string]?: JsonValue } | null;\n\n",
    );
    macro_rules! decl {
        ($($ty:ty),* $(,)?) => {
            $( out.push_str(&format!("export {}\n\n", <$ty as TS>::decl(&cfg))); )*
        };
    }
    decl!(
        // Domain
        BlockerRef,
        Issue,
        OrchestrationClaimState,
        RunAttemptPhase,
        TaskStatus,
        ProviderKind,
        ProviderCapabilities,
        ProviderProfile,
        ProviderAuthState,
        ProviderStatus,
        Project,
        Task,
        RunAttempt,
        LiveSession,
        RetryEntry,
        TokenUsage,
        AgentEvent,
        ApprovalRequest,
        ApprovalStatus,
        ApprovalDecision,
        ValidationResult,
        PullRequestReview,
        ChangedFileSummary,
        ReviewCommentEvaluation,
        MergeReadinessReport,
        HardwareSnapshot,
        ResourcePolicy,
        OrchestratorStateSnapshot,
        StateCounts,
        RunningSessionSummary,
        CodexTotals,
        AppSettings,
        WorktreeInfo,
        TaskDiff,
        RepositoryValidation,
        RuntimeInfo,
        // Workflow configuration
        ServiceConfig,
        HooksConfig,
        AgentConfig,
        CodexConfig,
        // Orchestrator responses
        IssueDetailResponse,
        WorkspaceInfo,
        AttemptSummary,
        RefreshResponse,
        WorkflowDocument,
        WorkflowValidation,
        ProjectUpdate,
        // HTTP request / response envelopes
        ApiErrorBody,
        ApiErrorDetail,
        HealthResponse,
        SchedulerStateResponse,
        CreateProjectRequest,
        ValidateRepositoryRequest,
        ListTasksQuery,
        CreateTaskRequest,
        MoveTaskStatusRequest,
        CancelTaskRequest,
        DecideApprovalRequest,
        UpdateWorkflowRequest,
        PreviewWorkflowRequest,
        SetCredentialRequest,
        CredentialKeysResponse,
        CredentialSavedResponse,
        StreamControlEvent,
    );
    out.trim_end().to_string() + "\n"
}

fn contract_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../packages/shared-types/src/generated/contracts.ts")
}

#[test]
fn typescript_contracts_are_up_to_date() {
    let generated = generate();
    let path = contract_path();
    if std::env::var("UPDATE_TS_CONTRACTS").is_ok() {
        std::fs::write(&path, &generated).expect("write generated contracts");
        return;
    }
    let committed = std::fs::read_to_string(&path)
        .unwrap_or_default()
        .replace("\r\n", "\n");
    assert!(
        committed == generated,
        "packages/shared-types/src/generated/contracts.ts is out of date with the Rust API types.\n\
         Run: UPDATE_TS_CONTRACTS=1 cargo test -p symphony-server --test ts_contract"
    );
}
