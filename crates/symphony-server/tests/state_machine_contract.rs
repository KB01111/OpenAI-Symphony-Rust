//! Checked task state-machine contract.
//!
//! HTTP payload types come from the OpenAPI document (`openapi_contract.rs`). The task state
//! machine is not an HTTP shape, so it is exported separately: `TaskStatus::allowed_transitions`
//! is rendered to `packages/shared-types/src/generated/stateMachine.ts` and this test fails when
//! that file is stale.
//!
//! Regenerate with:
//! `UPDATE_STATE_MACHINE=1 cargo test -p symphony-server --test state_machine_contract`

use std::path::PathBuf;

use symphony_core::domain::TaskStatus;

fn generate() -> String {
    let mut out = String::from(
        "// AUTO-GENERATED by crates/symphony-server/tests/state_machine_contract.rs. DO NOT EDIT.\n\
         // Regenerate: UPDATE_STATE_MACHINE=1 cargo test -p symphony-server --test state_machine_contract\n\n\
         import type { TaskStatus } from \"./openapi/types.gen.js\";\n\n",
    );
    out.push_str(&task_transition_table());
    out.trim_end().to_string() + "\n"
}

/// Emit `TaskStatus::allowed_transitions` so the UI validates drag-and-drop moves with the exact
/// Rust state machine instead of a hand-maintained copy. The server still enforces it.
fn task_transition_table() -> String {
    let all = [
        TaskStatus::Backlog,
        TaskStatus::Ready,
        TaskStatus::Queued,
        TaskStatus::Running,
        TaskStatus::Blocked,
        TaskStatus::HumanReview,
        TaskStatus::Completed,
        TaskStatus::Failed,
        TaskStatus::Cancelled,
    ];
    let mut out = String::from("export const ALL_TASK_STATUSES: ReadonlyArray<TaskStatus> = [");
    out.push_str(
        &all.iter()
            .map(|s| format!("\"{}\"", s.as_str()))
            .collect::<Vec<_>>()
            .join(", "),
    );
    out.push_str("];\n\n");
    out.push_str("export const TASK_STATUS_TRANSITIONS: Readonly<Record<TaskStatus, ReadonlyArray<TaskStatus>>> = {\n");
    for status in all {
        let targets = status
            .allowed_transitions()
            .iter()
            .map(|t| format!("\"{}\"", t.as_str()))
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!("  {}: [{}],\n", status.as_str(), targets));
    }
    out.push_str("};\n");
    out
}

fn contract_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../packages/shared-types/src/generated/stateMachine.ts")
}

#[test]
fn task_state_machine_is_up_to_date() {
    let generated = generate();
    let path = contract_path();
    if std::env::var("UPDATE_STATE_MACHINE").is_ok() {
        std::fs::write(&path, &generated).expect("write generated state machine");
        return;
    }
    let committed = std::fs::read_to_string(&path)
        .unwrap_or_default()
        .replace("\r\n", "\n");
    assert!(
        committed == generated,
        "packages/shared-types/src/generated/stateMachine.ts is out of date with TaskStatus::allowed_transitions.\n\
         Run: UPDATE_STATE_MACHINE=1 cargo test -p symphony-server --test state_machine_contract"
    );
}
